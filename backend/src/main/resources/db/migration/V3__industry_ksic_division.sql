-- 산업분류 기준을 KSIC 중분류(2자리)로 재정의한다.
-- V1 은 industry_code 를 DART induty_code(5자리 세분류)로 두었으나, API 명세의 industryCode 는
-- KSIC 중분류(division, 2자리) 다. 검색·상세·산업비교가 모두 이 축을 응답에 실으므로 여기서 바로잡는다.
--
-- 시드 출처: data/config/ksic_division.csv (S15P21A504-32). 중분류 77개.
-- 주의: company.industry_code 는 이제 2자리 division 을 담는다. 개발 DB 에 5자리로 수동 적재한
--       테스트 데이터가 있으면 FK 가 깨지므로, 이 마이그레이션 전에 industry/company 를 비우고 재적재한다.
--       (커밋된 스키마에는 industry/company 시드가 없어 신규 환경에서는 백필이 필요 없다.)

-- 원본 DART 세분류 코드(5자리)는 provenance 로 보존한다. 적재 파이프라인이 두 코드를 함께 채운다.
ALTER TABLE company ADD COLUMN induty_code VARCHAR(10);

COMMENT ON COLUMN company.induty_code    IS 'DART 기업개황 induty_code(5자리 세분류). 원본 보존용';
COMMENT ON COLUMN company.industry_code  IS 'KSIC 중분류 2자리. API 응답의 industryCode';
COMMENT ON TABLE  industry               IS 'KSIC 중분류 카탈로그. 동일 산업 비교(US-04)의 기준 축';
COMMENT ON COLUMN industry.industry_code IS 'KSIC 중분류 2자리 코드';

